// NPM Modules
import { Exclude } from 'class-transformer';
import { IsInt, IsNotEmpty, IsString } from 'class-validator';
import { Column, CreateDateColumn, Entity, JoinColumn, ManyToOne, PrimaryGeneratedColumn } from 'typeorm';
import 'reflect-metadata';

// Custom Modules
import Account from './account.entity';

/** One uploaded file: an organization logo now, a ticket attachment later. This row describes the file; the bytes live
 * in the private storage bucket under {@link Asset.storageKey}. Whatever uses the file points at its Asset (for
 * example `Organization.logo`), rather than the Asset recording what owns it, so every link is a real foreign key. */
@Entity()
export default class Asset {
    /** Primary key. Also what clients use to fetch the file, through `GET /asset/:assetID`. */
    @PrimaryGeneratedColumn('uuid')
    @IsNotEmpty()
    id: string;

    /** Where the file lives in the bucket, such as `assets/<uuid>`. Always generated by the API, never taken from the
     * client, and never serialized: clients only ever get short-lived signed links. */
    @Exclude()
    @Column({ unique: true })
    @IsString()
    @IsNotEmpty()
    storageKey: string;

    /** The file's name as uploaded, used as the download name. Shown back to people, never used as a storage path. */
    @Column()
    @IsString()
    @IsNotEmpty()
    fileName: string;

    /** The file's type, as detected from its contents when it was uploaded, not as claimed by the browser. */
    @Column()
    @IsString()
    @IsNotEmpty()
    contentType: string;

    /** The stored file's size in bytes. */
    @Column({ type: 'int' })
    @IsInt()
    size: number;

    /** The account that uploaded the file. Column saved in db will be `uploadedById`. */
    @ManyToOne(() => Account, { nullable: true })
    @JoinColumn()
    uploadedBy?: Account | null;

    /** Timestamp the file was uploaded. */
    @CreateDateColumn()
    createdOn: Date;
}
